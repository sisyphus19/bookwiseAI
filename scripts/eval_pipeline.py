"""
Small, reproducible evaluation of the BookWise pipeline against a RUNNING stack.

Because the catalog is metadata-only (title / author / rating / year), the test set uses title and
author queries whose correct answers can be verified from Books.csv. It measures:
  * retrieval hit-rate: how many of the top-K candidates match the expected author/title substring
  * retrieval latency and end-to-end /recommend latency (p50 / max)
  * LLM fallback rate, and an empty-result probe

Usage (stack up and ETL done):
  python scripts/eval_pipeline.py                       # defaults to http://localhost:8000
  python scripts/eval_pipeline.py --base http://localhost:8000 --k 5 --out docs/eval_results.md
"""
import argparse
import statistics
import time

import httpx

# (query, field, expected substring). Expectations were checked against data/raw/Books.csv.
CASES = [
    ("books by Suzanne Collins", "author", "suzanne collins"),
    ("J.K. Rowling novels", "author", "rowling"),
    ("Stephen King horror", "author", "stephen king"),
    ("Jane Austen", "author", "austen"),
    ("Tolkien fantasy", "author", "tolkien"),
    ("Dan Brown thrillers", "author", "dan brown"),
    ("George Orwell", "author", "orwell"),
    ("Agatha Christie mystery", "author", "christie"),
    ("Harry Potter", "title", "harry potter"),
    ("The Hobbit", "title", "hobbit"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://localhost:8000")
    ap.add_argument("--k", type=int, default=5)
    ap.add_argument("--out", default=None, help="write a markdown report here")
    args = ap.parse_args()
    api = f"{args.base}/api/v1"

    client = httpx.Client(timeout=60)
    print("stats:", client.get(f"{api}/stats").json(), "\n")

    rows, hit_total, rec_lat, fallbacks = [], 0, [], 0
    for query, field, needle in CASES:
        t0 = time.time()
        r = client.post(f"{api}/recommend", json={"query": query, "top_k": args.k})
        wall_ms = (time.time() - t0) * 1000
        data = r.json()
        recs = data.get("recommendations", [])
        hits = sum(1 for x in recs if needle in x["book"][field].lower())
        hit_total += hits
        rec_lat.append(wall_ms)
        fallbacks += bool(data.get("llm_fallback_used"))
        top = recs[0]["book"]["title"] if recs else "-"
        rows.append((query, hits, len(recs), data.get("total_candidates_retrieved", 0), round(wall_ms), data.get("llm_fallback_used"), top))
        print(f"{query:28s} hits={hits}/{len(recs)} cand={data.get('total_candidates_retrieved')} {wall_ms:7.0f} ms fallback={data.get('llm_fallback_used')} top={top}")

    # repeat one query to exercise the Redis cache
    t0 = time.time(); cached = client.post(f"{api}/recommend", json={"query": CASES[0][0], "top_k": args.k}).json()
    cache_ms = (time.time() - t0) * 1000

    # grounded QA + no-answer probe
    qa = client.post(f"{api}/catalog/ask", json={"question": "Which Suzanne Collins books are in the catalog?", "top_k": 5}).json()
    plot = client.post(f"{api}/catalog/ask", json={"question": "What is the plot of The Hunger Games?", "top_k": 3}).json()

    n = len(CASES) * args.k
    summary = [
        f"- Retrieval hit-rate (top-{args.k}, author/title match): **{hit_total}/{n} = {hit_total / n:.0%}**",
        f"- /recommend latency: p50 **{statistics.median(rec_lat):.0f} ms**, max **{max(rec_lat):.0f} ms** (n={len(rec_lat)})",
        f"- LLM fallback used: **{fallbacks}/{len(CASES)}** queries",
        f"- Repeat query cache_hit={cached.get('cache_hit')} in {cache_ms:.0f} ms",
        f"- /catalog/ask sources returned: {len(qa.get('sources', []))}; plot question answer (should decline, not invent): \"{plot.get('answer', '')[:200]}\"",
    ]
    print("\n" + "\n".join(summary))

    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write("# Evaluation results\n\nGenerated by `scripts/eval_pipeline.py` against a live stack.\n\n")
            f.write("\n".join(summary) + "\n\n| Query | Hits | Returned | Candidates | Latency ms | Fallback | Top result |\n|---|---|---|---|---|---|---|\n")
            for q, h, ret, cand, ms, fb, top in rows:
                f.write(f"| {q} | {h} | {ret} | {cand} | {ms} | {fb} | {top} |\n")
        print(f"\nWrote {args.out}")


if __name__ == "__main__":
    main()
